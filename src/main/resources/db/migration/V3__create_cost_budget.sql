-- Spending limits for recurring calendar periods, optionally scoped to one service and/or one
-- environment. A NULL scope column means "all"; environment '' means untagged costs.
CREATE TABLE cost_budget (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                      VARCHAR(100)   NOT NULL,
    limit_amount              NUMERIC(19, 2) NOT NULL,
    currency                  VARCHAR(3)     NOT NULL,
    period                    VARCHAR(16)    NOT NULL,
    service_name              VARCHAR(128),
    environment               VARCHAR(64),
    warning_threshold_percent INTEGER        NOT NULL DEFAULT 80,
    active                    BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at                TIMESTAMPTZ    NOT NULL,
    updated_at                TIMESTAMPTZ    NOT NULL,
    version                   BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT ck_cost_budget_name CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_cost_budget_limit CHECK (limit_amount > 0),
    CONSTRAINT ck_cost_budget_period CHECK (period IN ('MONTHLY', 'QUARTERLY', 'ANNUAL')),
    CONSTRAINT ck_cost_budget_threshold CHECK (warning_threshold_percent BETWEEN 1 AND 100),
    CONSTRAINT ck_cost_budget_currency CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE UNIQUE INDEX ux_cost_budget_name ON cost_budget (lower(name));
