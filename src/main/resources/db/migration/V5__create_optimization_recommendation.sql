-- Evidence-based optimization recommendations. The fingerprint identifies "the same
-- recommendation" across regeneration runs (rule + subject + period), so reviews are kept.
CREATE TABLE optimization_recommendation (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint               VARCHAR(300)   NOT NULL,
    rule_id                   VARCHAR(64)    NOT NULL,
    title                     VARCHAR(255)   NOT NULL,
    category                  VARCHAR(32)    NOT NULL,
    severity                  VARCHAR(8)     NOT NULL,
    service_name              VARCHAR(128),
    resource_id               VARCHAR(256),
    environment               VARCHAR(64),
    evidence_source           VARCHAR(32)    NOT NULL,
    evidence                  TEXT           NOT NULL,
    explanation               TEXT           NOT NULL,
    suggested_action          TEXT           NOT NULL,
    estimated_monthly_savings NUMERIC(19, 2),
    savings_basis             VARCHAR(500)   NOT NULL,
    period_start              DATE,
    period_end                DATE,
    status                    VARCHAR(16)    NOT NULL,
    status_note               VARCHAR(500),
    status_changed_at         TIMESTAMPTZ,
    created_at                TIMESTAMPTZ    NOT NULL,
    updated_at                TIMESTAMPTZ    NOT NULL,
    last_evaluated_at         TIMESTAMPTZ    NOT NULL,
    CONSTRAINT uk_optimization_recommendation_fingerprint UNIQUE (fingerprint),
    CONSTRAINT ck_optimization_recommendation_category CHECK (category IN
        ('COST_INCREASE', 'SCHEDULING', 'TAGGING', 'BUDGET', 'RIGHTSIZING', 'IDLE_RESOURCE')),
    CONSTRAINT ck_optimization_recommendation_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_optimization_recommendation_source CHECK (evidence_source IN
        ('BILLING_DATA', 'BUDGET_EVALUATION', 'UTILIZATION_DATA')),
    CONSTRAINT ck_optimization_recommendation_status CHECK (status IN ('OPEN', 'ACCEPTED', 'RESOLVED', 'DISMISSED')),
    CONSTRAINT ck_optimization_recommendation_savings CHECK (estimated_monthly_savings IS NULL
        OR estimated_monthly_savings >= 0)
);

CREATE INDEX ix_optimization_recommendation_status ON optimization_recommendation (status, severity);
