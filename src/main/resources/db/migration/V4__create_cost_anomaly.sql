-- Rule-based cost anomaly findings. One finding per dimension value and day; re-running
-- detection updates figures in place and keeps the review status.
CREATE TABLE cost_anomaly (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dimension         VARCHAR(16)    NOT NULL,
    dimension_value   VARCHAR(128)   NOT NULL,
    anomaly_date      DATE           NOT NULL,
    observed_amount   NUMERIC(19, 6) NOT NULL,
    baseline_amount   NUMERIC(19, 6) NOT NULL,
    increase_amount   NUMERIC(19, 6) NOT NULL,
    increase_percent  NUMERIC(12, 2),
    baseline_days     INTEGER        NOT NULL,
    severity          VARCHAR(8)     NOT NULL,
    reason            TEXT           NOT NULL,
    status            VARCHAR(16)    NOT NULL,
    review_note       VARCHAR(500),
    reviewed_at       TIMESTAMPTZ,
    detected_at       TIMESTAMPTZ    NOT NULL,
    updated_at        TIMESTAMPTZ    NOT NULL,
    CONSTRAINT uk_cost_anomaly UNIQUE (dimension, dimension_value, anomaly_date),
    CONSTRAINT ck_cost_anomaly_dimension CHECK (dimension IN ('SERVICE', 'ENVIRONMENT')),
    CONSTRAINT ck_cost_anomaly_severity CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH')),
    CONSTRAINT ck_cost_anomaly_status CHECK (status IN ('OPEN', 'ACKNOWLEDGED', 'DISMISSED')),
    CONSTRAINT ck_cost_anomaly_baseline_days CHECK (baseline_days > 0)
);

CREATE INDEX ix_cost_anomaly_date ON cost_anomaly (anomaly_date);
CREATE INDEX ix_cost_anomaly_status_date ON cost_anomaly (status, anomaly_date);
