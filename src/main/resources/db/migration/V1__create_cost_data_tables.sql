-- Cost data ingestion schema.
-- Conventions: timestamps are TIMESTAMPTZ and handled in UTC; usage dates are UTC calendar
-- days as reported by AWS; monetary amounts are NUMERIC (never floating point).
-- Optional text dimensions use '' (empty string) for "not reported" so that they can take
-- part in unique constraints; an empty environment means the cost carried no Environment tag.

CREATE TABLE cost_import_job (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source           VARCHAR(32)  NOT NULL,
    data_type        VARCHAR(16)  NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    file_name        VARCHAR(255),
    file_checksum    VARCHAR(64),
    period_start     DATE,
    period_end       DATE,
    records_received INTEGER      NOT NULL DEFAULT 0,
    records_inserted INTEGER      NOT NULL DEFAULT 0,
    records_skipped  INTEGER      NOT NULL DEFAULT 0,
    records_replaced INTEGER      NOT NULL DEFAULT 0,
    error_message    TEXT,
    started_at       TIMESTAMPTZ  NOT NULL,
    completed_at     TIMESTAMPTZ,
    removed_at       TIMESTAMPTZ,
    CONSTRAINT ck_cost_import_job_source CHECK (source IN ('CSV_UPLOAD', 'DEMO_SAMPLE', 'AWS_COST_EXPLORER')),
    CONSTRAINT ck_cost_import_job_data_type CHECK (data_type IN ('COST', 'UTILIZATION')),
    CONSTRAINT ck_cost_import_job_status CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED', 'REMOVED')),
    CONSTRAINT ck_cost_import_job_period CHECK (period_start IS NULL OR period_end IS NULL OR period_start <= period_end),
    CONSTRAINT ck_cost_import_job_counts CHECK (records_received >= 0 AND records_inserted >= 0
        AND records_skipped >= 0 AND records_replaced >= 0)
);

-- The same file content can only be imported once while its data is present.
-- Removing an import (status REMOVED) allows the file to be imported again.
CREATE UNIQUE INDEX ux_cost_import_job_file_checksum
    ON cost_import_job (data_type, file_checksum)
    WHERE status = 'COMPLETED' AND file_checksum IS NOT NULL;

CREATE INDEX ix_cost_import_job_started_at ON cost_import_job (started_at);

CREATE TABLE cost_record (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_job_id BIGINT         NOT NULL REFERENCES cost_import_job (id),
    source        VARCHAR(32)    NOT NULL,
    usage_date    DATE           NOT NULL,
    account_id    VARCHAR(12)    NOT NULL DEFAULT '',
    service_name  VARCHAR(128)   NOT NULL,
    region        VARCHAR(32)    NOT NULL DEFAULT '',
    environment   VARCHAR(64)    NOT NULL DEFAULT '',
    charge_type   VARCHAR(16)    NOT NULL,
    amount        NUMERIC(19, 6) NOT NULL,
    currency      VARCHAR(3)     NOT NULL,
    estimated     BOOLEAN        NOT NULL DEFAULT FALSE,
    ingested_at   TIMESTAMPTZ    NOT NULL,
    -- Natural key: one amount per source, day, account, service, region, environment and
    -- charge type. Re-importing overlapping data cannot create duplicates.
    CONSTRAINT uk_cost_record_natural_key
        UNIQUE (source, usage_date, account_id, service_name, region, environment, charge_type),
    CONSTRAINT ck_cost_record_source CHECK (source IN ('CSV_UPLOAD', 'DEMO_SAMPLE', 'AWS_COST_EXPLORER')),
    CONSTRAINT ck_cost_record_charge_type CHECK (charge_type IN ('USAGE', 'TAX', 'CREDIT', 'REFUND', 'NET')),
    CONSTRAINT ck_cost_record_service_name CHECK (service_name <> ''),
    CONSTRAINT ck_cost_record_currency CHECK (currency ~ '^[A-Z]{3}$')
);

CREATE INDEX ix_cost_record_usage_date ON cost_record (usage_date);
CREATE INDEX ix_cost_record_service_date ON cost_record (service_name, usage_date);
CREATE INDEX ix_cost_record_environment_date ON cost_record (environment, usage_date);
CREATE INDEX ix_cost_record_import_job ON cost_record (import_job_id);

-- Optional resource utilization measurements (for example average and peak CPU exported
-- from CloudWatch). Billing data alone cannot show utilization, so recommendations about
-- sizing are only produced for resources that have rows here.
CREATE TABLE resource_utilization (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_job_id   BIGINT         NOT NULL REFERENCES cost_import_job (id),
    resource_id     VARCHAR(256)   NOT NULL,
    resource_type   VARCHAR(64)    NOT NULL DEFAULT '',
    service_name    VARCHAR(128)   NOT NULL,
    environment     VARCHAR(64)    NOT NULL DEFAULT '',
    region          VARCHAR(32)    NOT NULL DEFAULT '',
    period_start    DATE           NOT NULL,
    period_end      DATE           NOT NULL,
    avg_cpu_percent NUMERIC(5, 2)  NOT NULL,
    max_cpu_percent NUMERIC(5, 2)  NOT NULL,
    period_cost     NUMERIC(19, 6),
    currency        VARCHAR(3),
    ingested_at     TIMESTAMPTZ    NOT NULL,
    CONSTRAINT uk_resource_utilization_period UNIQUE (resource_id, period_start, period_end),
    CONSTRAINT ck_resource_utilization_period CHECK (period_start <= period_end),
    CONSTRAINT ck_resource_utilization_cpu CHECK (avg_cpu_percent BETWEEN 0 AND 100
        AND max_cpu_percent BETWEEN 0 AND 100 AND avg_cpu_percent <= max_cpu_percent),
    CONSTRAINT ck_resource_utilization_cost CHECK (period_cost IS NULL OR (period_cost >= 0 AND currency IS NOT NULL))
);

CREATE INDEX ix_resource_utilization_period ON resource_utilization (period_end);
CREATE INDEX ix_resource_utilization_import_job ON resource_utilization (import_job_id);
